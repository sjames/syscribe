tc_TRS_BT_024() {
    local F="$1"
    local out rc
    _scn() { SCENARIO_NAME="$1"; printf "  ▶ %s\n" "$1"; }
    local U="$F/TC-TRS-BT-023/uav"
    local T; T=$(mktemp -d)
    exp() { "$SYSCRIBE" -m "$U" params export --config "$@" 2>&1; }
    # yq <file> <python expr over d> — evaluate against the parsed YAML
    yq() { python3 -I -c 'import sys,yaml;d=yaml.safe_load(open(sys.argv[1]));print(eval(sys.argv[2]))' "$1" "$2"; }

    _scn "two exports of the same model are byte-identical"
    exp CONF-UAV-DEPLOY-001 >"$T/a.yaml"; exp CONF-UAV-DEPLOY-001 >"$T/b.yaml"
    [ -s "$T/a.yaml" ] && cmp -s "$T/a.yaml" "$T/b.yaml" && pass "identical bytes" || fail "exports differ or are empty"

    _scn "the header names the Configuration, the stage and the content hash"
    grep -q '^# configuration: CONF-UAV-DEPLOY-001$' "$T/a.yaml" && grep -q '^# stage: load$' "$T/a.yaml" && pass "configuration and stage" || fail "header wrong: $(head -5 "$T/a.yaml")"
    grep -Eq '^# projection-hash: blake3:[0-9a-f]{64}$' "$T/a.yaml" && pass "projection-hash is a blake3 digest" || fail "no blake3 hash"
    head -1 "$T/a.yaml" | grep -q '^# Generated by syscribe' && pass "generator named" || fail "no generator line"

    _scn "keys are sorted"
    [ "$(yq "$T/a.yaml" "list(d['parameters'])")" = "$(yq "$T/a.yaml" "sorted(d['parameters'])")" ] && pass "sorted feature keys" || fail "unsorted"
    rm -rf "$T"
}
