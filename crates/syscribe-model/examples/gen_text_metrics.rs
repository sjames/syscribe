//! Regenerates `src/vis/metrics_table.rs`, the bundled advance widths of Liberation Sans (GH #339).
//!
//! `cargo run -p syscribe-model --example gen_text_metrics -- <LiberationSans-Regular.ttf> <LiberationSans-Bold.ttf>
//! > crates/syscribe-model/src/vis/metrics_table.rs`
//!
//! Only the advance widths are taken (no outlines): one number per character and weight, so diagram sizing is the
//! same on every machine whatever fonts it has installed.

use ab_glyph::{Font, FontRef};

/// U+0020–U+017F (Basic Latin, Latin-1, Latin Extended-A), then the punctuation and symbols diagram labels use.
fn chars() -> Vec<char> {
    let mut v: Vec<char> = (0x20u32..=0x7E).chain(0xA0..=0x17F).filter_map(char::from_u32).collect();
    v.extend("‐–—‘’‚“”„•…‰‹›€™←↑→↓↔⇒≈≠≤≥−×÷±°µΩαβγδεθλμπστφω√∞".chars());
    v.sort();
    v.dedup();
    v
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let regular = std::fs::read(&args[1]).expect("regular face");
    let bold = std::fs::read(&args[2]).expect("bold face");
    let r = FontRef::try_from_slice(&regular).expect("parse regular");
    let b = FontRef::try_from_slice(&bold).expect("parse bold");
    let upem = r.units_per_em().expect("units per em");
    println!("//! Advance widths of Liberation Sans Regular and Bold (SIL Open Font License 1.1; metric-compatible with");
    println!("//! Arial and Helvetica), in font units. Generated by `examples/gen_text_metrics.rs`; do not edit (GH #339).");
    println!();
    println!("pub const UNITS_PER_EM: f64 = {upem:.1};");
    println!();
    println!("/// `(character, regular advance, bold advance)`, sorted by character.");
    println!("pub const ADVANCES: &[(char, u16, u16)] = &[");
    for c in chars() {
        let (gr, gb) = (r.glyph_id(c), b.glyph_id(c));
        if gr.0 == 0 || gb.0 == 0 {
            continue;
        }
        let esc: String = c.escape_unicode().collect();
        println!("    ('{esc}', {}, {}),", r.h_advance_unscaled(gr).round() as u16, b.h_advance_unscaled(gb).round() as u16);
    }
    println!("];");
}
